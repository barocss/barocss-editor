import { chromium } from '@playwright/test';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } });
await p.goto('http://localhost:5182/', { waitUntil: 'networkidle' });
await p.waitForTimeout(1200);
const sel = () => p.evaluate(() => JSON.stringify(window.editor?.selection));
const row = p.locator('[data-frame="desktop"] .st-page > .st-stack').nth(1);
await row.locator('h3').first().click({ force: true });
await p.waitForTimeout(300);
console.log('after click :', await sel());
await p.keyboard.press('Control+d');
await p.waitForTimeout(600);
console.log('after ctrl+d:', await sel());
console.log('sections    :', await p.locator('[data-frame="desktop"] .st-page > .st-stack').count());
await p.keyboard.press('Delete');
await p.waitForTimeout(600);
console.log('after delete:', await sel());
console.log('sections    :', await p.locator('[data-frame="desktop"] .st-page > .st-stack').count());
console.log('model page  :', await p.evaluate(() => {
  const ed = window.editor, st = ed.dataStore;
  const root = st.getNode(ed.getRootId());
  const page = (root.content ?? []).map((s) => st.getNode(s)).find((n) => n?.stype === 'surface');
  return (page.content ?? []).map((s) => st.getNode(s)?.stype).join(',');
}));
await b.close();
