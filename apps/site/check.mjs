import { chromium } from '@playwright/test';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } });
await p.goto('http://localhost:5182/', { waitUntil: 'networkidle' });
await p.waitForTimeout(1200);
const row = p.locator('[data-frame="desktop"] .st-page > .st-stack').nth(1);
const model = () => p.evaluate(() => {
  const ed = window.editor, st = ed.dataStore;
  const walk = (sid, out = []) => { const n = st.getNode(sid); if (!n) return out;
    if (n.stype === 'frame' && (n.content ?? []).length === 3) out.push(sid);
    for (const c of n.content ?? []) if (typeof c === 'string') walk(c, out); return out; };
  const rowSid = walk(ed.getRootId())[0];
  const text = (sid) => { const n = st.getNode(sid); if (n?.text) return n.text;
    for (const c of n?.content ?? []) if (typeof c === 'string') { const t = text(c); if (t) return t; } };
  return st.getNode(rowSid).content.map(text);
});
console.log('model before:', await model());
console.log('dom   before:', await row.locator('h3').allTextContents());
await p.evaluate(() => {
  const ed = window.editor, st = ed.dataStore;
  const walk = (sid, out = []) => { const n = st.getNode(sid); if (!n) return out;
    if (n.stype === 'frame' && (n.content ?? []).length === 3) out.push(sid);
    for (const c of n.content ?? []) if (typeof c === 'string') walk(c, out); return out; };
  const rowSid = walk(ed.getRootId())[0];
  const first = st.getNode(rowSid).content[0];
  return ed.executeCommand('moveBlockInto', { nodeId: first, parentId: rowSid, index: 2 });
});
await p.waitForTimeout(700);
console.log('model after :', await model());
console.log('dom   after :', await row.locator('h3').allTextContents());
await b.close();
